/**
 * Generates src/styles/tokens.css and src/styles/theme.css from src/tokens/index.ts.
 *
 *   node scripts/build-tokens.ts           write the files
 *   node scripts/build-tokens.ts --check   fail if the committed files are out of date (CI/build)
 *
 * Runs on Node 24 with built-in TypeScript type stripping (no extra tooling).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { bestTextColor, SCALE_STEPS } from "../src/theme/color.ts";
import {
  brand,
  elevation,
  motion,
  neutral,
  PREFIX,
  radius,
  semantic,
  spacing,
  status,
  typography,
} from "../src/tokens/index.ts";

const HEADER =
  "/* GENERATED by scripts/build-tokens.ts from src/tokens/index.ts. Do not edit. */\n";
const darkText = neutral[950];

const decl = (name: string, value: string) => `  --${PREFIX}-${name}: ${value};`;

function baseVariables(): string[] {
  const lines: string[] = [];
  for (const [step, value] of Object.entries(neutral)) lines.push(decl(`neutral-${step}`, value));
  for (const step of SCALE_STEPS) lines.push(decl(`primary-${step}`, brand[step]));
  lines.push(decl("on-primary-600", bestTextColor(brand[600], ["#ffffff", darkText])));
  lines.push(decl("on-primary-500", bestTextColor(brand[500], ["#ffffff", darkText])));
  for (const [name, scale] of Object.entries(status)) {
    for (const step of SCALE_STEPS) lines.push(decl(`${name}-${step}`, scale[step]));
    lines.push(decl(`on-${name}-600`, bestTextColor(scale[600], ["#ffffff", darkText])));
    lines.push(decl(`on-${name}-500`, bestTextColor(scale[500], ["#ffffff", darkText])));
  }
  lines.push(decl("font-sans", typography.fontSans));
  lines.push(decl("font-display", typography.fontDisplay));
  lines.push(decl("font-mono", typography.fontMono));
  for (const [key, [size, leading]] of Object.entries(typography.scale)) {
    lines.push(decl(`text-${key}`, size));
    lines.push(decl(`leading-${key}`, leading));
  }
  for (const [key, value] of Object.entries(typography.weights))
    lines.push(decl(`weight-${key}`, value));
  for (const [key, value] of Object.entries(typography.tracking))
    lines.push(decl(`tracking-${key}`, value));
  for (const [key, value] of Object.entries(spacing)) {
    lines.push(decl(`space-${String(key).replace(".", "_")}`, value));
  }
  for (const [key, value] of Object.entries(radius)) lines.push(decl(`radius-${key}`, value));
  for (const [key, value] of Object.entries(motion.duration))
    lines.push(decl(`duration-${key}`, value));
  for (const [key, value] of Object.entries(motion.easing)) lines.push(decl(`ease-${key}`, value));
  lines.push(decl("logo-url", "none"));
  return lines;
}

function themeVariables(theme: "light" | "dark"): string[] {
  const lines = Object.entries(semantic[theme]).map(([role, value]) => decl(role, value));
  for (const [level, value] of Object.entries(elevation[theme]))
    lines.push(decl(`shadow-${level}`, value));
  lines.push(`  color-scheme: ${theme};`);
  return lines;
}

function tokensCss(): string {
  const reduced = Object.keys(motion.duration).map((key) => decl(`duration-${key}`, "0ms"));
  return `${HEADER}
:root {
${[...baseVariables(), ...themeVariables("light")].join("\n")}
}

/* Dark theme: explicit [data-theme="dark"], or the OS preference unless light is forced. */
[data-theme="dark"] {
${themeVariables("dark").join("\n")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${themeVariables("dark")
  .map((line) => `  ${line}`)
  .join("\n")}
  }
}

/* Motion is decorative only; honour the user's reduced-motion setting everywhere. */
@media (prefers-reduced-motion: reduce) {
  :root {
${reduced.map((line) => `  ${line}`).join("\n")}
  }
}
`;
}

function themeCss(): string {
  const v = (name: string) => `var(--${PREFIX}-${name})`;
  const colors: string[] = [
    "  --color-white: #ffffff;",
    "  --color-black: #000000;",
    "  --color-transparent: transparent;",
    "  --color-current: currentColor;",
  ];
  for (const step of Object.keys(neutral))
    colors.push(`  --color-neutral-${step}: ${v(`neutral-${step}`)};`);
  for (const step of SCALE_STEPS)
    colors.push(`  --color-primary-${step}: ${v(`primary-${step}`)};`);
  for (const name of Object.keys(status)) {
    for (const step of SCALE_STEPS)
      colors.push(`  --color-${name}-${step}: ${v(`${name}-${step}`)};`);
  }
  for (const role of Object.keys(semantic.light)) colors.push(`  --color-${role}: ${v(role)};`);

  const type = Object.keys(typography.scale).flatMap((key) => [
    `  --text-${key}: ${v(`text-${key}`)};`,
    `  --text-${key}--line-height: ${v(`leading-${key}`)};`,
  ]);

  return `${HEADER}
/* Tailwind v4 theme: utilities resolve to the runtime CSS variables in tokens.css, so tenant
   theming and dark mode need no rebuild. Default Tailwind colours are removed on purpose. */
@theme {
  --color-*: initial;
}

@theme inline {
${colors.join("\n")}

  --font-sans: ${v("font-sans")};
  --font-display: ${v("font-display")};
  --font-mono: ${v("font-mono")};
${type.join("\n")}

${Object.keys(radius)
  .map((key) => `  --radius-${key}: ${v(`radius-${key}`)};`)
  .join("\n")}

${Object.keys(elevation.light)
  .map((level) => `  --shadow-${level}: ${v(`shadow-${level}`)};`)
  .join("\n")}

${Object.keys(motion.easing)
  .map((key) => `  --ease-${key}: ${v(`ease-${key}`)};`)
  .join("\n")}

  --animate-fade-in: sp-fade-in ${v("duration-base")} ${v("ease-standard")};
  --animate-fade-out: sp-fade-out ${v("duration-fast")} ${v("ease-exit")};
  --animate-scale-in: sp-scale-in ${v("duration-base")} ${v("ease-emphasized")};
  --animate-slide-in-right: sp-slide-in-right ${v("duration-slow")} ${v("ease-standard")};
  --animate-slide-in-left: sp-slide-in-left ${v("duration-slow")} ${v("ease-standard")};
  --animate-slide-in-bottom: sp-slide-in-bottom ${v("duration-slow")} ${v("ease-standard")};

  @keyframes sp-fade-in { from { opacity: 0; } to { opacity: 1; } }
  @keyframes sp-fade-out { from { opacity: 1; } to { opacity: 0; } }
  @keyframes sp-scale-in { from { opacity: 0; transform: scale(0.96) translateY(4px); } to { opacity: 1; transform: none; } }
  @keyframes sp-slide-in-right { from { transform: translateX(100%); } to { transform: none; } }
  @keyframes sp-slide-in-left { from { transform: translateX(-100%); } to { transform: none; } }
  @keyframes sp-slide-in-bottom { from { transform: translateY(100%); } to { transform: none; } }
}

@layer base {
  html {
    font-family: ${v("font-sans")};
    background-color: ${v("bg")};
    color: ${v("fg")};
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
    text-rendering: optimizeLegibility;
  }
  h1, h2, h3, h4 {
    font-family: ${v("font-display")};
    letter-spacing: ${v("tracking-tight")};
  }
  ::selection {
    background-color: ${v("primary-subtle")};
    color: ${v("primary-subtle-fg")};
  }
  :focus-visible {
    outline: 2px solid ${v("ring")};
    outline-offset: 2px;
  }
}
`;
}

const root = fileURLToPath(new URL("..", import.meta.url));
const outputs: [string, string][] = [
  [`${root}src/styles/tokens.css`, tokensCss()],
  [`${root}src/styles/theme.css`, themeCss()],
];

function readOrEmpty(path: string): string {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

const check = process.argv.includes("--check");
let stale = false;
for (const [path, content] of outputs) {
  if (check) {
    if (readOrEmpty(path) !== content) {
      stale = true;
      console.error(`Out of date: ${path} (run npm run tokens)`);
    }
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
