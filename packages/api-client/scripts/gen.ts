/**
 * Generates src/generated/schema.d.ts from the running API's OpenAPI document.
 *
 *   npm run gen -w packages/api-client
 *   API_OPENAPI_URL=https://portal.localhost/api/v1/openapi.json npm run gen -w packages/api-client
 *
 * The OpenAPI endpoint is only served outside production (FRD §7.1), so generate against a dev
 * or staging API. Uses the openapi-typescript JS API so it works the same on Windows and Unix.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const source = process.env["API_OPENAPI_URL"] ?? "http://127.0.0.1:8000/api/v1/openapi.json";
const outDir = fileURLToPath(new URL("../src/generated/", import.meta.url));
const banner = `/**\n * GENERATED by scripts/gen.ts from ${source}. Do not edit.\n * Regenerate after API changes: npm run gen -w packages/api-client\n */\n\n`;

const ast = await openapiTS(new URL(source));
mkdirSync(outDir, { recursive: true });
writeFileSync(`${outDir}schema.d.ts`, banner + astToString(ast));
console.log(`wrote ${outDir}schema.d.ts from ${source}`);
